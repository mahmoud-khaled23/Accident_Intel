// Damage-domain type definitions for Accident-Intel

/** A single damaged component on the vehicle */
export interface DamagePart {
  id: string;
  name: string; // e.g. "Front Bumper"
  location: string; // e.g. "Front", "Rear", "Driver side"
  damageType: string; // e.g. "Dent", "Scratch", "Crack", "Shatter"
  severity: 'minor' | 'moderate' | 'severe';
  confidence: number; // AI detection confidence 0–1
  /** Normalized position on the vehicle image for overlay marker (0–1) */
  normalizedX?: number;
  normalizedY?: number;
  source: 'ai' | 'user';
}

/** A single line item in a repair cost breakdown */
export interface RepairLineItem {
  id: string;
  partId?: string; // links back to a DamagePart
  description: string;
  category: 'parts' | 'labor' | 'paint' | 'other' | 'tax';
  unitCost: number; // USD
  quantity: number;
  total: number; // unitCost * quantity
}

/** Aggregated repair cost estimate */
export interface RepairEstimate {
  /** Always provided by the API (number, may be 0 for a no-detection run) */
  subtotal: number; // USD, before tax
  tax: number; // USD
  total: number; // USD, after tax
  lowEstimate: number; // USD
  highEstimate: number; // USD
  currency: string; // "USD"
  /** Omitted by the real backend; may be explicitly null — render N/A */
  egpEquivalent?: number | null; // EGP equivalent at time of estimate
  egpRate?: number | null; // exchange rate used
  assumptions: string[];
  limitations: string[];
}

/** Basic vehicle identification information */
export interface VehicleInfo {
  make: string; // e.g. "Toyota"
  model: string; // e.g. "Camry"
  year: number;
  color: string;
  /** Odometer reading in km — null when the user did not provide one */
  mileage?: number | null;
  /** null when not provided */
  vin?: string | null;
  /** e.g. "Cairo", "Alexandria" — null when not provided */
  repairLocation?: string | null;
}

/** One segmentation overlay view produced by the backend viz pipeline */
export type SegmentationView = 'parts' | 'damage' | 'combined';

/**
 * Segmentation overlays for a single uploaded photo.
 * Each key is the URL of that view's overlay image; views are omitted when
 * the pipeline could not produce them (e.g. unreadable photo).
 * - `parts`:    all car-part masks with names
 * - `damage`:   damage masks with class + confidence labels
 * - `combined`: parts faint underneath, damage on top, "damage -> part"
 */
export interface SegmentationImages {
  photo: string; // original uploaded filename
  parts?: string;
  damage?: string;
  combined?: string;
}

/** Full damage assessment record */
export interface DamageAssessmentRecord {
  id: string;
  sessionId: string;
  vehicleInfo: VehicleInfo;
  imageUrls: string[]; // base64 data URLs or placeholder paths
  /** Mask-overlay images generated by the segmentation models (real mode) */
  segmentationImages?: SegmentationImages[];
  damagedParts: DamagePart[];
  repairItems: RepairLineItem[];
  estimate: RepairEstimate;
  assessmentDate: string; // ISO 8601
  isDemoData?: boolean;
}
