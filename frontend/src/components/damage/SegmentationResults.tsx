import { ExternalLink } from 'lucide-react';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import type { DamageAssessmentRecord, SegmentationView } from '@/types/damage';

interface SegmentationResultsProps {
  record: DamageAssessmentRecord;
}

interface ViewMeta {
  key: SegmentationView;
  label: string;
  hint: string;
}

/** The three overlay images written by the backend viz pipeline, in order. */
const VIEWS: ViewMeta[] = [
  {
    key: 'parts',
    label: 'Part masks',
    hint: 'Car parts found by the parts-segmentation model',
  },
  {
    key: 'damage',
    label: 'Damage masks',
    hint: 'Damage instances with class and confidence labels',
  },
  {
    key: 'combined',
    label: 'Combined overlay',
    hint: 'Damage masks mapped onto their parts (“damage → part”)',
  },
];

/** Damage-class colours — mirrors DAMAGE_COLORS in src/car_damage_cost/viz.py */
const DAMAGE_LEGEND: { name: string; hex: string }[] = [
  { name: 'Crack', hex: '#ff0000' },
  { name: 'Dent', hex: '#ff8c00' },
  { name: 'Glass shatter', hex: '#00ffff' },
  { name: 'Lamp broken', hex: '#ffff00' },
  { name: 'Scratch', hex: '#ff00ff' },
  { name: 'Tire flat', hex: '#00ff00' },
];

/**
 * Displays the segmented car-damage images generated by the backend after
 * analysis: part masks, damage masks, and the combined overlay per photo.
 * Renders nothing when the record has no segmentation images (mock mode or
 * legacy records).
 */
export function SegmentationResults({ record }: SegmentationResultsProps) {
  const photos = (record.segmentationImages ?? []).filter((entry) =>
    VIEWS.some((view) => entry[view.key]),
  );
  if (photos.length === 0) return null;

  return (
    <Card>
      <CardHeader>
        <CardTitle>Segmentation Results</CardTitle>
        <p className="text-xs text-slate-400">
          Masks produced by the damage- and parts-segmentation models for each uploaded
          photo. Click an image to view it full size.
        </p>
      </CardHeader>
      <CardContent className="space-y-6">
        {photos.map((entry) => (
          <div key={entry.photo} className="space-y-2">
            <p className="text-xs font-mono text-slate-500 truncate">{entry.photo}</p>
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
              {VIEWS.filter((view) => entry[view.key]).map((view) => (
                <a
                  key={view.key}
                  href={entry[view.key]}
                  target="_blank"
                  rel="noreferrer"
                  className="group block"
                  title={`${view.hint} — open full size`}
                >
                  <div className="relative overflow-hidden rounded-lg border border-[#1e2d45] bg-[#0d1525]">
                    <img
                      src={entry[view.key]}
                      alt={`${view.label} for ${entry.photo}`}
                      loading="lazy"
                      className="w-full h-40 sm:h-44 object-contain transition-transform duration-150 group-hover:scale-[1.02]"
                    />
                    <span className="absolute right-1.5 top-1.5 rounded-md bg-black/60 p-1 text-slate-300 opacity-0 transition-opacity group-hover:opacity-100">
                      <ExternalLink className="h-3 w-3" />
                    </span>
                  </div>
                  <p className="mt-1 text-[11px] font-medium text-slate-300">{view.label}</p>
                  <p className="text-[11px] text-slate-500">{view.hint}</p>
                </a>
              ))}
            </div>
          </div>
        ))}

        {/* Colour legend for the damage-mask classes */}
        <div className="flex flex-wrap items-center gap-x-4 gap-y-1.5 border-t border-[#1e2d45] pt-3">
          <span className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider">
            Damage colours
          </span>
          {DAMAGE_LEGEND.map((item) => (
            <span key={item.name} className="inline-flex items-center gap-1.5 text-[11px] text-slate-400">
              <span
                className="h-2.5 w-2.5 rounded-sm border border-white/20"
                style={{ backgroundColor: item.hex }}
              />
              {item.name}
            </span>
          ))}
        </div>
      </CardContent>
    </Card>
  );
}
